"""Create Mesen-only stage-ending QA launchers for the final Korean ROM.

The tool does not modify or duplicate the ROM. It changes the Japanese build's
runtime level byte during the initial loader and uses the game's own level-clear
entity trigger when Select is pressed.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "build" / "Battletoads_KR_dev.nes"
OUT = ROOT / "work" / "qa" / "stage_end"
SOURCE_SHA256 = "300D7A335E404FCBA4522D21AB58AF1DC77140DD7C4A6DE4EA7331E50B6E5090"

STAGES = [
    (1, "RAGNAROK'S CANYON"),
    (2, "WOOKIE HOLE"),
    (3, "TURBO TUNNEL"),
    (4, "ARCTIC CAVERNS"),
    (5, "SURF CITY"),
    (6, "KARNATH'S LAIR"),
    (7, "VOLKMIRE'S INFERNO"),
    (8, "INTRUDER EXCLUDER"),
    (9, "TERRA TUBES"),
    (10, "RAT RACE"),
    (11, "CLINGER-WINGER"),
    (12, "THE REVOLUTION"),
    (13, "ARMAGEDDON"),
    (14, "LEVEL 14 / ENDING"),
]

LUA_TEMPLATE = r'''-- Generated by workspace/scripts/make_stage_qa.py
local TARGET = @@TARGET@@
local frame = 0
local select_latched = false

local function select_pressed(value)
  -- This title stores Select as $20 in its post-read controller byte.
  return (value % 0x40) >= 0x20
end

emu.addMemoryCallback(function()
  local buttons = emu.read(0x15, emu.memType.nesMemory)

  -- Deterministically leave the title screen and advance the first briefing.
  if (frame >= 1550 and frame <= 1556) or
     (frame >= 1900 and frame <= 1906) then
    emu.write(0x15, 0x10, emu.memType.nesMemory)
    emu.write(0x2B, 0x10, emu.memType.nesMemory)
    return
  end

  if frame >= 2200 then
    local pressed = select_pressed(buttons)
    if pressed and not select_latched then
      -- $7F in entity slot 0 invokes the game's normal level-clear path.
      emu.write(0x03C3, 0x7F, emu.memType.nesMemory)
    end
    select_latched = pressed
  end
end, emu.callbackType.exec, 0x8D87)

emu.addEventCallback(function()
  frame = frame + 1

  -- Keep the selected level stable across the level-name call and the loader's
  -- default stage-1 initialization.
  if frame >= 1850 and frame <= 1910 then
    emu.write(0x000D, TARGET, emu.memType.nesMemory)
  end
end, emu.eventType.startFrame)
'''


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main() -> None:
    if sha256(SOURCE) != SOURCE_SHA256:
        raise SystemExit("최종 한글 ROM SHA-256 불일치")

    OUT.mkdir(parents=True, exist_ok=True)
    scripts = OUT / "scripts"
    scripts.mkdir(exist_ok=True)
    for old in scripts.glob("stage_*.lua"):
        old.unlink()

    manifest = []
    for stage, name in STAGES:
        script = scripts / f"stage_{stage:02d}.lua"
        script.write_text(
            LUA_TEMPLATE.replace("@@TARGET@@", str(stage)), encoding="utf-8"
        )
        manifest.append({"stage": stage, "name": name, "script": script.name})

    fast_launcher = r'''@echo off
setlocal
set "ROOT=%~dp0..\..\.."
set "ROM=%ROOT%\build\Battletoads_KR_dev.nes"
set "MESEN=H:\Mesen\Mesen.exe"

if not exist "%ROM%" (
  echo [ERROR] Final Korean ROM not found: "%ROM%"
  pause
  exit /b 1
)
if not exist "%MESEN%" (
  echo [ERROR] Mesen not found: "%MESEN%"
  echo Edit MESEN in this file if your emulator is installed elsewhere.
  pause
  exit /b 1
)

echo Battletoads Korean - Stage Ending QA
echo.
echo  1 Ragnarok's Canyon       8 Intruder Excluder
echo  2 Wookie Hole             9 Terra Tubes
echo  3 Turbo Tunnel           10 Rat Race
echo  4 Arctic Caverns         11 Clinger-Winger
echo  5 Surf City              12 The Revolution
echo  6 Karnath's Lair         13 Armageddon
echo  7 Volkmire's Inferno
echo 14 Level 14 / Ending
echo.
set /p "STAGE=Stage number [1-14]: "
set "NUM=0"
set /a NUM=STAGE 2>nul
if %NUM% LSS 1 goto invalid
if %NUM% GTR 14 goto invalid
if %NUM% LSS 10 set "NUM=0%NUM%"

start "Battletoads Stage QA" "%MESEN%" --testRunner "%~dp0scripts\stage_%NUM%.lua" "%ROM%"
exit /b 0

:invalid
echo [ERROR] Enter a number from 1 to 14.
pause
exit /b 1
'''
    (OUT / "run_stage_selector_fast.cmd").write_text(fast_launcher, encoding="ascii")

    launcher = r'''@echo off
setlocal
set "ROOT=%~dp0..\..\.."
set "ROM=%ROOT%\build\Battletoads_KR_dev.nes"
set "MESEN=H:\Mesen\Mesen.exe"

if not exist "%ROM%" goto missing_rom
if not exist "%MESEN%" goto missing_mesen

echo Battletoads Korean - Stage Ending Savestate QA
echo.
echo  1 Ragnarok's Canyon       8 Intruder Excluder
echo  2 Wookie Hole             9 Terra Tubes
echo  3 Turbo Tunnel           10 Rat Race
echo  4 Arctic Caverns         11 Clinger-Winger
echo  5 Surf City              12 The Revolution
echo  6 Karnath's Lair         13 Armageddon
echo  7 Volkmire's Inferno
echo 14 Level 14 / Ending
echo.
set /p "STAGE=Stage number [1-14]: "
set "NUM=0"
set /a NUM=STAGE 2>nul
if %NUM% LSS 1 goto invalid
if %NUM% GTR 14 goto invalid
if %NUM% LSS 10 set "NUM=0%NUM%"
set "STATE=%~dp0states\stage_%NUM%_end.mss"
if not exist "%STATE%" goto missing_state

start "Battletoads Stage Ending QA" "%MESEN%" "%ROM%"
powershell.exe -NoProfile -Command "Start-Sleep -Seconds 2"
explorer.exe /select,"%STATE%"
echo.
echo Mesen: Load State From File, then choose the selected .mss file.
exit /b 0

:missing_rom
echo [ERROR] Final Korean ROM not found: "%ROM%"
goto fail
:missing_mesen
echo [ERROR] Mesen not found: "%MESEN%"
goto fail
:missing_state
echo [ERROR] Stage state not found: "%STATE%"
goto fail
:invalid
echo [ERROR] Enter a number from 1 to 14.
:fail
pause
exit /b 1
'''
    (OUT / "run_stage_end_qa.cmd").write_text(launcher, encoding="ascii")

    readme = """Battletoads 한글판 스테이지 종료 검수 도구

1. run_stage_end_qa.cmd를 실행하고 1~14 중 검수할 스테이지를 입력합니다.
2. Mesen과 선택한 .mss 파일이 있는 탐색기가 열립니다.
3. Mesen의 Load State From File에서 탐색기에 선택된 .mss 파일을 불러옵니다.
4. 해당 스테이지의 클리어 직전 상태부터 정상 속도로 종료 대사/전환을 확인합니다.

주의
- 세이브는 실제 보스 직전 체크포인트가 아니라 게임 자체의 클리어 트리거를 기록한 직후입니다.
- 최종 한글 ROM 전용이며 ROM 자체는 변경하지 않습니다.
- Mesen 기본 경로는 H:\\Mesen\\Mesen.exe입니다. 다른 위치라면 CMD의 MESEN 항목을 수정하세요.
- 배포용 파일이 아닌 내부 검수 전용입니다.
- run_stage_selector_fast.cmd는 자동 선택/SELECT 트리거 조사용이며 빠르게 실행됩니다. 실제 플레이 검수에는 run_stage_end_qa.cmd와 states 폴더를 사용하세요.
"""
    (OUT / "README_KO.txt").write_text(readme, encoding="utf-8-sig")
    (OUT / "manifest.json").write_text(
        json.dumps(
            {
                "source": str(SOURCE.relative_to(ROOT)),
                "source_sha256": SOURCE_SHA256,
                "emulator": r"H:\Mesen\Mesen.exe",
                "method": {
                    "level_ram": "0x000D",
                    "override_frames": "1850-1910",
                    "clear_trigger": "write 0x7F once to 0x03C3 on Select",
                },
                "stages": manifest,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"generated {len(STAGES)} stage QA scripts: {OUT}")


if __name__ == "__main__":
    main()



